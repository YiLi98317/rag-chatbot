def flow_ecommerce_assets(product_name="", selling_points="", image_desc=""):
    """
    完整三步工作流：产品识别 → 10屏提示词 → 出图指引
    返回三段 Markdown，可直接发给门店老板
    """
    # 第一步
    report = generate_product_report(product_name, selling_points, image_desc)
    
    # 第二步
    if product_name:
        prompt_hint = product_name
    elif selling_points:
        prompt_hint = f"主打{selling_points}的产品"
    else:
        prompt_hint = "手机"
    screens = generate_10_screens(prompt_hint)
    
    # 组装
    full_output = f"""# 🛒 电商素材生成 - 三步工作流

---

{report}

---

{screens}

---

## ⚡ 快速上手（一键复制）

老板，上面是完整的电商素材方案。操作流程：
1. **先看「产品识别报告」**确认产品信息无误
2. **复制「10屏提示词」**里每一屏的「中文提示词」到即梦/Lovart 生成
3. 需要修改哪个屏的描述，直接跟我说

如果产品信息填得不够详细，告诉我要补充什么～
"""
    return full_output
